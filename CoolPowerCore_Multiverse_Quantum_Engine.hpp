// Deep Quantum Tunneling Mechanic:
// Harvests 33.6 kV ZVS plasma-cavitation vacuum fluctuations + 4H-SiC betavoltaic flux
// across deployed Cool Power Core units to phase-shift player mass & cargo across variants.
class QuantumTunnelingDrive {
public:
    static constexpr double CPC_BASE_THERMAL_W = 382.93;
    static constexpr double ZVS_PLASMA_KV      = 33.60;

    static void tickCoherence(SharedEconomyLedger& ledger, double dtSeconds, HardwareTier tier) noexcept {
        if (ledger.quantumTunnelUnlocked) {
            ledger.quantumCoherencePct = 100.0;
            return;
        }
        // Coherence builds passively from deployed cores + supercapacitor ZVS resonance
        double tierBonus = 1.0 + 0.25 * static_cast<double>(tier);
        double coreFactor = std::min(5.0, static_cast<double>(ledger.coresDeployed) / 25.0);
        ledger.quantumCoherencePct = std::min(100.0, ledger.quantumCoherencePct + dtSeconds * 0.45 * coreFactor * tierBonus);
        if (ledger.quantumCoherencePct >= 35.0 && ledger.quantumTunnelTier < 1) ledger.quantumTunnelTier = 1;
        if (ledger.quantumCoherencePct >= 70.0 && ledger.quantumTunnelTier < 2) ledger.quantumTunnelTier = 2;
        if (ledger.quantumCoherencePct >= 100.0 && ledger.cpcBalance >= 250.0) {
            ledger.quantumTunnelTier = 3;
        }
    }

    static bool tryUnlockQuantumTunnel(SharedEconomyLedger& ledger) noexcept {
        constexpr double UNLOCK_COST_CPC = 250.0;
        if (ledger.quantumTunnelUnlocked) return true;
        if (ledger.quantumCoherencePct >= 100.0 && ledger.cpcBalance >= UNLOCK_COST_CPC) {
            ledger.cpcBalance -= UNLOCK_COST_CPC; // Recycled 100% into global CPC-COIN reserve NAV
            ledger.quantumTunnelUnlocked = true;
            ledger.quantumTunnelTier = 3;
            return true;
        }
        return false;
    }

    static bool quantumJumpToVariant(
        SharedEconomyLedger& ledger,
        GameVariant& activeVariant,
        GameVariant targetVariant,
        double& energyReservePct
    ) noexcept {
        if (activeVariant == targetVariant) return true;
        // Free switching at hub before deep-dive, OR instant field phase-tunneling once unlocked
        if (ledger.quantumTunnelUnlocked) {
            if (energyReservePct < 15.0) return false;
            energyReservePct -= 15.0; // 15% ZVS phase-pulse draw, instantly regenerated by CPC cores
            activeVariant = targetVariant;
            return true;
        }
        // Standard hub selection preserves 100% of SharedEconomyLedger across all 4 variants
        activeVariant = targetVariant;
        return true;
    }
};

